/*
 * 内存复制函数 memcpy 的实现
 *
 * 功能：将指定长度的字节从源地址复制到目标地址
 * 注意：此实现假设源地址和目标地址不重叠（如需处理重叠内存，请使用 memmove）
 */

/*
 * 重要注意事项：
 * memcpy(dest, src, n) 假设数据段寄存器 ds 和附加段寄存器 es 指向相同的常规数据段。
 * 这一假设适用于：
 * - 所有内核函数（ds = es = 内核空间，fs = 本地数据，gs = 空）
 * - 所有行为良好的用户程序（ds = es = 用户数据空间）
 *
 * 这并非设计缺陷，因为任何修改 es 寄存器且不谨慎处理的用户程序，
 * 其崩溃是预期且合理的结果。
 */

